"""
    magnetic_field(time::Real, longitude::Real, latitude::Real, altitude::Real;
        isv::Integer=0, itype::Integer=1, version="igrf14syn")

Compute the earth magnetic field at a given time and location. The
application range extends from year 1900 to 2035, with dates outside this range
resulting in `inclination` and `declination` being set to 0.0, and intensity
being set to `1.0e8`.  The results are only considered to be definitive from year
1945 to 2020 (inclusive).

At its core, function uses a translation by Claude of the Fortran source file
(`R/igrf14.f` in oce), although the input arguments and return value were
adjusted to be closer to the oce function named `magneticField`.
(Permission to use that Fortran code in the oce package was granted by
the respective authors.) The following quotes from the original
Fortran source summarize the methodology employed and names
some of the authors of that Fortran code.

1. "This is a synthesis routine for the 14th generation IGRF as agreed in
   December 2024 by IAGA Working Group V-MOD."

2. "Adapted from 8th generation version to include new maximum degree for
   main-field models for 2000.0 and onwards and use WGS84 spheroid instead of
   International Astronomical Union 1966 spheroid as recommended by IAGA in
   July 2003. Reference radius remains as 6371.2 km - it is NOT the mean
   radius (= 6371.0 km) but 6371.2 km is what is used in determining the
   coefficients. Adaptation by Susan Macmillan, August 2003 (for 9th
   generation), December 2004, December 2009 & December 2014; by
   William Brown, December 2019, February 2020. Updated by Ciaran
   Beggan, November 2024."

# Arguments

- `time` a decimal year (this can be constructed from a DateTime using
  `GMT.DateTime`).  The valid range extends from 1900.0 to 2035.0. Outside that
  range, the angles are set to zero and the intensity is set to `1e8`. The
  Fortran source declares the results to be degraded after year 2030.
- `longitude` longitude in degrees East.
- `latitude` latitude in degrees North.
- `altitude` height above sealevel in km (if `itype=1`) or distance from earth
  centre (if `itype=2`).

# Keywords

The defaults are likely preferable for most applications,

- `isv`: `0` for main-field values, `1` for secular-variation values.
- `itype`: `1` for geodetic (WGS84 spheroid) input, `2` for geocentric.
- `version` a String that must be `"igrf14syn"`. (This is to allow future
  versions of the magnetic-field formulae.)

# Returns

A NamedTuple containing `declination` (angle in degrees from North),
`inclination` (angle in degrees above the horizon) and `intensity)` (in
nanoTesla). If `time` is less than 1900 or greater than 2035, then a warning is
issued, with `declination` and `inclination` being set to `0.0` and with
`intensity` being set to `1.0e8`.

# Examples
```julia
using OceanAnalysis, Dates
time = 2026.0
longitude = -63.0
latitude = 45.0
altitude = 0.0
declination, inclination, intensity = magnetic_field(time, longitude, latitude, altitude)
# EXPECT, from oce:
#  magneticField(time=2026.0, longitude=-63.0, latitude=45.0)
#     declination -16.32922, inclination 66.44525, intensity 51110.98
"
```
"""
function magnetic_field(time::Real, longitude::Real, latitude::Real, altitude::Real;
    isv::Integer=0, itype::Integer=1, version="igrf14syn")
    isv == 0 || isv == 1 || error("isv must be 0 (for mean field) or 1 (for secular variation)")
    itype == 1 || itype == 2 || error("itype must be 1 (for geodetic input) or 2 (for geocentric input")
    version == "igrf14syn" || error("version must be \"igrf14syn\"")
    date = isa(time, DateTime) ? GMT.yeardecimal(time) : time
    x = 0.0
    y = 0.0
    z = 0.0
    colat = 90.0 - latitude
    date = time
    if date < 1900.0 || date > 2035.0
        @warn "Time is not in the range from 1900 to 2035"
        return (0.0, 0.0, 0.0, 1.0e8)
    end

    local t::Float64, tc::Float64, ll::Int, nmx::Int, nc::Int, kmx::Int

    if date < 2025.0
        t = 0.2 * (date - 1900.0)
        ll_epoch = floor(Int, t)
        one = float(ll_epoch)
        t = t - one

        if date < 1995.0
            # SH models before 1995.0 are only to degree 10
            nmx = 10
            nc = nmx * (nmx + 2)
            ll = nc * ll_epoch
            kmx = (nmx + 1) * (nmx + 2) ÷ 2
        else
            nmx = 13
            nc = nmx * (nmx + 2)
            ll_epoch2 = floor(Int, 0.2 * (date - 1995.0))
            # 19 is the number of SH models that extend to degree 10
            ll = 120 * 19 + nc * ll_epoch2
            kmx = (nmx + 1) * (nmx + 2) ÷ 2
        end
        tc = 1.0 - t
        if isv == 1
            tc = -0.2
            t = 0.2
        end
    else
        t = date - 2025.0
        tc = 1.0
        if isv == 1
            t = 1.0
            tc = 0.0
        end
        # pointer for last coefficient in pen-ultimate set of MF coefficients...
        ll = 3450
        nmx = 13
        nc = nmx * (nmx + 2)
        kmx = (nmx + 1) * (nmx + 2) ÷ 2
    end

    r = float(altitude)
    one = colat * 0.017453292
    ct = cos(one)
    st = sin(one)
    one = longitude * 0.017453292

    cl = zeros(Float64, 13)
    sl = zeros(Float64, 13)
    cl[1] = cos(one)
    sl[1] = sin(one)

    cd = 1.0
    sd = 0.0
    l = 1
    m = 1
    n = 0

    if itype != 2
        # conversion from geodetic to geocentric coordinates (WGS84 spheroid)
        a2 = 40680631.6
        b2 = 40408296.0
        one = a2 * st * st
        two = b2 * ct * ct
        three = one + two
        rho = sqrt(three)
        r = sqrt(altitude * (altitude + 2.0 * rho) + (a2 * one + b2 * two) / three)
        cd = (altitude + rho) / r
        sd = (a2 - b2) / rho * ct * st / r
        one = ct
        ct = ct * cd - st * sd
        st = st * cd + one * sd
    end

    ratio = 6371.2 / r
    rr = ratio * ratio

    # computation of Schmidt quasi-normal coefficients p and q(=x in the Fortran)
    p = zeros(Float64, 105)
    q = zeros(Float64, 105)
    p[1] = 1.0
    p[3] = st
    q[1] = 0.0
    q[3] = ct
    global fn, gn

    for k in 2:kmx
        if n < m
            m = 0
            n += 1
            rr *= ratio
            fn = float(n)
            gn = float(n - 1)
        end
        fm = float(m)

        if m == n
            if k != 3
                one = sqrt(1.0 - 0.5 / fm)
                j = k - n - 1
                p[k] = one * st * p[j]
                q[k] = one * (st * q[j] + ct * p[j])
                cl[m] = cl[m-1] * cl[1] - sl[m-1] * sl[1]
                sl[m] = sl[m-1] * cl[1] + cl[m-1] * sl[1]
            end
        else
            gmm = fm * fm
            one = sqrt(fn * fn - gmm)
            two = sqrt(gn * gn - gmm) / one
            three = (fn + gn) / one
            i = k - n
            j = i - n + 1
            p[k] = three * ct * p[i] - two * p[j]
            q[k] = three * (ct * q[i] - st * p[i]) - two * q[j]
        end

        # synthesis of x, y and z in geocentric coordinates
        lm = ll + l
        one = (tc * GH[lm] + t * GH[lm+nc]) * rr
        if m == 0
            x += one * q[k]
            z -= (fn + 1.0) * one * p[k]
            l += 1
        else
            two = (tc * GH[lm+1] + t * GH[lm+nc+1]) * rr
            three = one * cl[m] + two * sl[m]
            x += three * q[k]
            z -= (fn + 1.0) * three * p[k]
            if st != 0.0
                y += (one * sl[m] - two * cl[m]) * fm * p[k] / st
            else
                y += (one * sl[m] - two * cl[m]) * q[k] * ct
            end
            l += 2
        end
        m += 1
    end

    # conversion to coordinate system specified by itype
    one = x
    x = x * cd + z * sd
    z = z * cd - one * sd
    intensity = sqrt(x * x + y * y + z * z)
    # final conversion to variables used in R/oce
    declination = rad2deg(atan(y, x))
    inclination = rad2deg(atan(z, sqrt(x^2 + y^2)))
    return (declination=declination, inclination=inclination, intensity=intensity)
end
export magnetic_field


